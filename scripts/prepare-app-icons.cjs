const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/constants/app-icon-paths.ts'), 'utf8');
const shapes = Array.from(source.matchAll(/^  (\w+): '([^']+)',?$/gm), ([, name, shape]) => ({ name, shape }));
if (!shapes.length) throw Error('No app icon geometry found.');

const output = path.join(root, 'assets/images/icons');
fs.mkdirSync(output, { recursive: true });
const entries = [];
for (const { name, shape } of shapes) {
  const file = `${name}.svg`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" color="#112F6F" stroke="#112F6F" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">${shape}</svg>`;
  fs.writeFileSync(path.join(output, file), `${svg}\n`);
  entries.push(`  ${name}: require('@/assets/images/icons/${file}'),`);
}
fs.writeFileSync(path.join(root, 'src/constants/app-icon-assets.ts'),
  `// Generated by scripts/prepare-app-icons.cjs from app-icon-paths.ts.\nexport const appIconAssets = {\n${entries.join('\n')}\n} as const;\n`);
